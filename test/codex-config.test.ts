// The configuration for Codex, through installCodex and verifyCodexConfig, with temporary homes.

import assert from "node:assert/strict";
import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import { test, type TestContext } from "node:test";
import { type CodexRun, installCodex, verifyCodexConfig } from "../core/accounts/providers/codex-config.ts";
import { mcpSystem } from "../core/global.ts";
import { state } from "../core/state.ts";
import { REPO, quiet } from "./helpers.ts";

// This side's home with CODEX_HOME unset, and another home standing for the other side, which
// install never writes.
function sides(t: TestContext) {
  const root = fs.mkdtempSync(path.join(os.tmpdir(), "dotagents-codex-config-"));
  const home = path.join(root, "here");
  const other = path.join(root, "there");
  fs.mkdirSync(home);
  fs.mkdirSync(other);
  const saved = { HOME: process.env.HOME, USERPROFILE: process.env.USERPROFILE, CODEX_HOME: process.env.CODEX_HOME };
  Object.assign(process.env, { HOME: home, USERPROFILE: home });
  delete process.env.CODEX_HOME;
  t.after(() => {
    for (const [k, v] of Object.entries(saved)) v === undefined ? delete process.env[k] : (process.env[k] = v);
    fs.rmSync(root, { recursive: true, force: true });
  });
  return { home, other };
}

const never = () => false;
const agents = (home: string) => path.join(home, ".codex", "AGENTS.md");
const snapshot = (dir: string): string[] => fs.readdirSync(dir, { recursive: true, withFileTypes: true }).map((e) => path.join(e.parentPath, e.name)).sort();

test("install writes the instructions and the rules for Codex on this side, never the other side's", (t) => {
  const { home, other } = sides(t);
  fs.mkdirSync(path.join(home, ".codex"));
  fs.mkdirSync(path.join(other, ".codex"));
  quiet();
  installCodex(REPO, { onPath: never });
  assert.equal(state.problems, 0);
  const text = fs.readFileSync(agents(home), "utf8");
  assert.match(text, /^<!-- generated by dotagents/);
  assert.match(text, /# Global instructions/);
  assert.match(text, /# Rules/);
  assert.match(text, /# Commit convention|Commit/i);
  assert.doesNotMatch(text, /These apply to Claude Code on this machine/);
  // The other side writes its own when install runs there, as with Claude Code's folder.
  assert.deepEqual(fs.readdirSync(path.join(other, ".codex")), []);
});

test("install leaves the skills to the workspaces: nothing in ~/.agents/skills", (t) => {
  const { home } = sides(t);
  fs.mkdirSync(path.join(home, ".codex"));
  quiet();
  installCodex(REPO, { onPath: never });
  assert.equal(fs.existsSync(path.join(home, ".agents")), false);
});

test("a second install changes nothing", (t) => {
  const { home, other } = sides(t);
  fs.mkdirSync(path.join(home, ".codex"));
  fs.mkdirSync(path.join(other, ".codex"));
  quiet();
  installCodex(REPO, { onPath: never });
  const before = fs.readFileSync(agents(home), "utf8");
  const files = snapshot(home);
  const events = quiet();
  installCodex(REPO, { onPath: never });
  assert.deepEqual(events.filter((e) => e.kind === "result" && e.status !== "ok"), []);
  assert.equal(fs.readFileSync(agents(home), "utf8"), before);
  assert.deepEqual(snapshot(home), files);
});

test("--dry-run touches nothing", (t) => {
  const { home, other } = sides(t);
  fs.mkdirSync(path.join(home, ".codex"));
  fs.mkdirSync(path.join(other, ".codex"));
  const before = [snapshot(home), snapshot(other)];
  quiet({ dryRun: true });
  installCodex(REPO, { onPath: never });
  assert.deepEqual([snapshot(home), snapshot(other)], before);
});

test("without Codex installed nothing is created", (t) => {
  const { home, other } = sides(t);
  quiet();
  installCodex(REPO, { onPath: never });
  assert.deepEqual(snapshot(home), []);
  assert.deepEqual(snapshot(other), []);
});

test("the codex command on the PATH is enough to install on this side", (t) => {
  const { home } = sides(t);
  quiet();
  installCodex(REPO, { onPath: () => true });
  assert.ok(fs.existsSync(agents(home)));
});

test("an older generated file is replaced and a foreign one is backed up", (t) => {
  const { home } = sides(t);
  fs.mkdirSync(path.join(home, ".codex"));
  fs.writeFileSync(agents(home), "<!-- generated by dotagents: edit the source in the dotagents repository and run it again -->\n# Old\n");
  quiet();
  installCodex(REPO, { onPath: never });
  assert.deepEqual(fs.readdirSync(path.join(home, ".codex")), ["AGENTS.md"]);
  assert.match(fs.readFileSync(agents(home), "utf8"), /# Global instructions/);

  fs.writeFileSync(agents(home), "My own notes\n");
  quiet();
  installCodex(REPO, { onPath: never });
  const backups = fs.readdirSync(path.join(home, ".codex")).filter((n) => n.startsWith("AGENTS.md.bak-"));
  assert.equal(backups.length, 1);
  assert.equal(fs.readFileSync(path.join(home, ".codex", backups[0]), "utf8"), "My own notes\n");
});

test("check fails on a missing or old file, warns on an override, passes after install", (t) => {
  const { home } = sides(t);
  fs.mkdirSync(path.join(home, ".codex"));
  let events = quiet();
  verifyCodexConfig(REPO, { onPath: never });
  assert.equal(state.problems, 1); // no AGENTS.md

  quiet();
  installCodex(REPO, { onPath: never });
  fs.writeFileSync(path.join(home, ".codex", "AGENTS.override.md"), "Use tabs.\n");
  events = quiet();
  verifyCodexConfig(REPO, { onPath: never });
  assert.equal(state.problems, 0);
  assert.ok(events.some((e) => e.kind === "warning" && /instead of AGENTS.md/.test(e.text)));

  fs.appendFileSync(agents(home), "stale\n");
  quiet();
  verifyCodexConfig(REPO, { onPath: never });
  assert.equal(state.problems, 1);
});

test("check says nothing when Codex isn't installed", (t) => {
  sides(t);
  const events = quiet();
  verifyCodexConfig(REPO, { onPath: never });
  assert.deepEqual(events, []);
});

// A codex command that keeps its MCP servers in memory, as `mcp list --json` and `mcp add` see them.
function fakeCodex(servers: Record<string, object>) {
  const calls: string[][] = [];
  const run: CodexRun = (args) => {
    calls.push(args);
    if (args[1] === "list") return JSON.stringify(Object.entries(servers).map(([name, transport]) => ({ name, transport })));
    const [, , name, ...rest] = args;
    if (rest[0] === "--url") servers[name] = { type: "streamable_http", url: rest[1] };
    else {
      const at = rest.indexOf("--");
      const env = Object.fromEntries(rest.slice(0, at).filter((_, i) => i % 2).map((kv) => kv.split("=")));
      // Codex keeps the env sorted by key
      const keys = Object.keys(env).sort();
      servers[name] = { type: "stdio", command: rest[at + 1], args: rest.slice(at + 2), env: keys.length ? Object.fromEntries(keys.map((k) => [k, env[k]])) : null };
    }
    return "";
  };
  return { run, calls, servers };
}

test("install gives Codex the configuration's MCP servers through codex mcp add, once, leaving its own alone; check sees them", (t) => {
  const { home } = sides(t);
  fs.mkdirSync(path.join(home, ".codex"));
  const config = path.join(home, "config");
  fs.cpSync(path.join(REPO, "templates", "config"), config, { recursive: true });
  const system = mcpSystem();
  fs.writeFileSync(path.join(config, "claude", "mcp-servers.json"), JSON.stringify({
    browser: { [system]: { command: "npx", args: ["-y", "browser-mcp@1"], env: { ZONE: "b", DEBUG: "1" } } },
    docs: { [system]: { url: "https://example.com/mcp", type: "http" } },
    elsewhere: { "some-other-os": { command: "y" } },
  }));
  const saved = process.env.DOTAGENTS_CONFIG;
  process.env.DOTAGENTS_CONFIG = config;
  t.after(() => void (process.env.DOTAGENTS_CONFIG = saved));
  const own = { type: "stdio", command: "mine", args: [], env: null };
  const codex = fakeCodex({ own });

  const mcpCheck = (events: ReturnType<typeof quiet>) => events.find((e) => e.kind === "check" && e.text.startsWith("Codex has the MCP servers")) as { passed: boolean; detail: string } | undefined;
  let events = quiet();
  verifyCodexConfig(REPO, { onPath: never, run: codex.run });
  assert.deepEqual({ ...mcpCheck(events) }, { kind: "check", passed: false, text: "Codex has the MCP servers of the configuration: browser", detail: "add browser with: dotagents install" });

  // --dry-run doesn't even run codex, which writes in its folder to list
  const before = codex.calls.length;
  quiet({ dryRun: true });
  installCodex(REPO, { onPath: never, run: codex.run });
  assert.equal(codex.calls.length, before);

  events = quiet();
  installCodex(REPO, { onPath: never, run: codex.run });
  // A remote server goes to Codex by hand: it may carry headers, or start a sign-in
  assert.deepEqual(codex.calls.filter((c) => c[1] === "add"), [["mcp", "add", "browser", "--env", "ZONE=b", "--env", "DEBUG=1", "--", "npx", "-y", "browser-mcp@1"]]);
  assert.ok(events.some((e) => e.kind === "result" && e.status === "skipped" && e.detail.startsWith("add docs to Codex by hand")));
  assert.deepEqual(codex.servers.own, own);

  const adds = codex.calls.length;
  quiet();
  installCodex(REPO, { onPath: never, run: codex.run });
  assert.equal(codex.calls.slice(adds).filter((c) => c[1] === "add").length, 0, "a second install changes nothing");
  events = quiet();
  verifyCodexConfig(REPO, { onPath: never, run: codex.run });
  assert.equal(mcpCheck(events)?.passed, true);
  assert.equal(state.problems, 0);

  // A codex that doesn't answer is said, not taken for nothing to do
  events = quiet();
  verifyCodexConfig(REPO, { onPath: never, run: () => null });
  assert.ok(events.some((e) => e.kind === "warning" && e.text.startsWith("Codex's MCP servers can't be read")));
});
