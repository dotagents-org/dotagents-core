// The second Desktop app per profile, through the profiles module, with a fake shortcut adapter
// (any system) and, on Windows, the real PowerShell one.

import assert from "node:assert/strict";
import { spawnSync } from "node:child_process";
import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import { test, type TestContext } from "node:test";
import { dropProfile, installProfiles, launcherDir, setUpProfile } from "../core/profiles.ts";
import { type Shortcut, type Shortcuts, profileIcon, appTitle, desktopDataDir, desktopExe, desktopLauncherFile, powershellShortcuts, shortcutFile, trayStartupFile } from "../core/desktop.ts";
import { state } from "../core/state.ts";
import { taskbarWatcher, taskbarWatcherFile } from "../core/taskbar.ts";
import { REPO, quiet } from "./helpers.ts";

function tempWindowsHome(t: TestContext, { withDesktop = true } = {}) {
  const home = fs.mkdtempSync(path.join(os.tmpdir(), "dotagents-desktop-"));
  const keys = ["HOME", "USERPROFILE", "APPDATA", "LOCALAPPDATA", "DOTAGENTS_STATE_DIR"] as const;
  const saved = Object.fromEntries(keys.map((k) => [k, process.env[k]]));
  Object.assign(process.env, {
    HOME: home,
    USERPROFILE: home,
    APPDATA: path.join(home, "AppData", "Roaming"),
    LOCALAPPDATA: path.join(home, "AppData", "Local"),
    DOTAGENTS_STATE_DIR: path.join(home, "state"),
  });
  t.after(() => {
    for (const [k, v] of Object.entries(saved)) v === undefined ? delete process.env[k] : (process.env[k] = v);
    fs.rmSync(home, { recursive: true, force: true });
  });
  if (withDesktop) {
    fs.mkdirSync(path.dirname(desktopExe()), { recursive: true });
    fs.writeFileSync(desktopExe(), "");
  }
  return home;
}

// Keeps the shortcuts in memory, and leaves a file where each one would be.
function fakeShortcuts() {
  const saved = new Map<string, Shortcut>();
  const shortcuts: Shortcuts = {
    read: (lnk) => saved.get(lnk) ?? null,
    write: (lnk, s) => {
      saved.set(lnk, { ...s });
      fs.writeFileSync(lnk, "lnk");
    },
  };
  return { saved, desktop: { shortcuts } };
}

test("every profile gets a Start menu shortcut, \"Claude <Name>\"; only the second one a data folder of its own", (t) => {
  tempWindowsHome(t);
  const { saved, desktop } = fakeShortcuts();
  quiet();
  setUpProfile(REPO, { name: "work", isDefault: true, desktop });
  setUpProfile(REPO, { name: "personal", desktop });
  assert.equal(state.problems, 0);
  assert.ok(shortcutFile("personal").endsWith("Claude Personal.lnk"));
  assert.equal(appTitle("my-work"), "Claude My Work");
  // The default profile opens the normal app, with its own data and ~/.claude.
  assert.equal(saved.get(shortcutFile("work"))?.description, "dotagents:work");
  assert.ok(!fs.existsSync(desktopDataDir("work")));
  const defaultVbs = fs.readFileSync(desktopLauncherFile(launcherDir(), "work"), "utf8");
  assert.ok(defaultVbs.includes('.Remove "CLAUDE_CONFIG_DIR"'));
  assert.ok(!defaultVbs.includes("--user-data-dir"));
  assert.match(defaultVbs, /-AppId ""dotagents\.claude\.work""/);
  assert.doesNotMatch(defaultVbs, /-DataDir/);
  assert.ok(fs.existsSync(desktopDataDir("personal")));
  const vbs = fs.readFileSync(desktopLauncherFile(launcherDir(), "personal"), "utf8");
  // Every app's Code tab uses ~/.claude; the data folder keeps the app's own sign-in apart.
  assert.ok(vbs.includes('.Remove "CLAUDE_CONFIG_DIR"'));
  assert.ok(vbs.includes(`--user-data-dir=""${desktopDataDir("personal")}""`));
  const lnk = saved.get(shortcutFile("personal"));
  assert.equal(lnk?.description, "dotagents:personal");
  assert.ok(lnk?.args.includes("claude-desktop-personal.vbs"));
  // Its own taskbar button: the shortcut's app ID, and the launcher starts the watcher with it.
  assert.equal(lnk?.appId, "dotagents.claude.personal");
  assert.match(vbs, /claude-taskbar\.ps1"" -AppId ""dotagents\.claude\.personal"" -DisplayName ""Claude Personal"".* -DataDir ""[^"]*Claude-personal""", 0, False/);
  const watcher = fs.readFileSync(taskbarWatcherFile(launcherDir()), "utf8").split("\n");
  assert.match(watcher[1], /generated by dotagents/);
  // No assets/claude-personal.ico: the app's icon. The repository's own profiles have theirs.
  assert.equal(lnk?.icon, `${desktopExe()},0`);
  assert.equal(profileIcon(REPO, "lovelace"), `${path.join(REPO, "assets", "claude-lovelace.ico")},0`);

  // A second run changes nothing.
  quiet();
  setUpProfile(REPO, { name: "personal", desktop });
  assert.equal(state.counts.created, undefined);
  assert.equal(state.counts.updated, undefined);
});

test("the app's execution alias counts as installed, though stat can't follow it", { skip: process.platform === "win32" }, (t) => {
  tempWindowsHome(t, { withDesktop: false });
  // Like the alias: lstat finds it, fs.existsSync doesn't.
  fs.mkdirSync(path.dirname(desktopExe()), { recursive: true });
  fs.symlinkSync(path.join(os.tmpdir(), "nowhere-dotagents"), desktopExe());
  assert.equal(fs.existsSync(desktopExe()), false);
  const { saved, desktop } = fakeShortcuts();
  quiet();
  setUpProfile(REPO, { name: "personal", desktop });
  assert.ok(saved.has(shortcutFile("personal")));
});

test("a dry run makes no folder, launcher or shortcut", (t) => {
  tempWindowsHome(t);
  const { saved, desktop } = fakeShortcuts();
  quiet({ dryRun: true });
  setUpProfile(REPO, { name: "personal", desktop });
  assert.ok(!fs.existsSync(desktopDataDir("personal")));
  assert.equal(saved.size, 0);
});

test("a shortcut someone else made with the same name is left alone", (t) => {
  tempWindowsHome(t);
  const { saved, desktop } = fakeShortcuts();
  fs.mkdirSync(path.dirname(shortcutFile("personal")), { recursive: true });
  desktop.shortcuts.write(shortcutFile("personal"), { target: "x.exe", args: "", description: "mine", icon: "", appId: "" });
  quiet();
  setUpProfile(REPO, { name: "personal", desktop });
  assert.equal(saved.get(shortcutFile("personal"))?.description, "mine");
  assert.equal(state.counts.skipped, 1);
});

test("without Claude Desktop, only a note: no shortcut and no failure", (t) => {
  tempWindowsHome(t, { withDesktop: false });
  const { saved, desktop } = fakeShortcuts();
  quiet();
  setUpProfile(REPO, { name: "personal", desktop });
  assert.equal(state.problems, 0);
  assert.equal(state.counts.warnings, 1);
  assert.equal(saved.size, 0);
});

test("removing the profile removes its launcher and shortcut, never the data folder", (t) => {
  tempWindowsHome(t);
  const { desktop } = fakeShortcuts();
  quiet();
  setUpProfile(REPO, { name: "personal", desktop });
  dropProfile("personal", { desktop });
  assert.ok(!fs.existsSync(shortcutFile("personal")));
  assert.ok(!fs.existsSync(desktopLauncherFile(launcherDir(), "personal")));
  assert.ok(fs.existsSync(desktopDataDir("personal")));
});

test("the PowerShell adapter writes a shortcut and reads it back", { skip: process.platform !== "win32" }, (t) => {
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), "dotagents-lnk-"));
  t.after(() => fs.rmSync(dir, { recursive: true, force: true }));
  const lnk = path.join(dir, "Claude test.lnk");
  const wanted = { target: path.join(process.env.SystemRoot ?? "C:\\Windows", "System32", "wscript.exe"), args: '"C:\\x y\\a.vbs"', description: "dotagents:test", icon: "C:\\Windows\\notepad.exe,0", appId: "dotagents.claude.test" };
  powershellShortcuts.write(lnk, wanted);
  const read = powershellShortcuts.read(lnk);
  assert.equal(read?.description, "dotagents:test");
  assert.equal(read?.args, wanted.args);
  assert.equal(read?.target.toLowerCase(), wanted.target.toLowerCase());
  // The AppUserModelID, written through the shortcut's property store, reads back.
  assert.equal(read?.appId, "dotagents.claude.test");
});

test("the taskbar watcher compiles and ends on its own when no Claude instance shows up", { skip: process.platform !== "win32", timeout: 120_000 }, (t) => {
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), "dotagents-taskbar-"));
  t.after(() => fs.rmSync(dir, { recursive: true, force: true }));
  const script = path.join(dir, "claude-taskbar.ps1");
  fs.writeFileSync(script, taskbarWatcher());
  const args = ["-NoProfile", "-NonInteractive", "-ExecutionPolicy", "Bypass", "-File", script];
  const params = ["-AppId", "dotagents.claude.ci", "-DisplayName", "Claude Ci", "-Icon", "C:\\x.ico", "-Launcher", "C:\\x.vbs", "-DataDir", "C:\\nowhere\\Claude-ci", "-StartupSeconds", "2"];
  const res = spawnSync("powershell.exe", [...args, ...params], { encoding: "utf8", timeout: 110_000 });
  assert.equal(res.status, 0, res.stderr);
});

test("install takes away the dropped tray panel's launcher, but not a file there that isn't dotagents'", (t) => {
  tempWindowsHome(t);
  const launcher = trayStartupFile();
  fs.mkdirSync(path.dirname(launcher), { recursive: true });
  fs.writeFileSync(launcher, "' The dotagents tray panel, started with Windows.\r\n' generated by dotagents: edit the source in the dotagents repository and run it again\r\n");
  quiet({ dryRun: true });
  installProfiles(REPO, { desktop: fakeShortcuts().desktop });
  assert.ok(fs.existsSync(launcher), "a dry run removes nothing");
  quiet();
  installProfiles(REPO, { desktop: fakeShortcuts().desktop });
  assert.ok(!fs.existsSync(launcher));
  fs.writeFileSync(launcher, "' someone else's\r\n");
  quiet();
  installProfiles(REPO, { desktop: fakeShortcuts().desktop });
  assert.ok(fs.existsSync(launcher), "not dotagents': kept");
});
