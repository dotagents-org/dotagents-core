// Where Codex reads its configuration, and what `install` puts there. Codex has no rules folder,
// so the rules of the configuration go at the end of the one instructions file. The skills reach
// Codex as they reach Claude Code, per workspace: Codex reads .agents/skills in the repository and
// the folders above it, where the workspace standard links them. The accounts of Codex are in
// codex.ts.

import fs from "node:fs";
import path from "node:path";
import { configRoot, writeGenerated } from "./common.ts";
import { renderInstructions } from "./global.ts";
import { type Peer, loadMachine } from "./machine-state.ts";
import { codexHome } from "./codex.ts";
import { checkItem, checkWarn, displayPath, section } from "./output.ts";
import { inWsl } from "./peer.ts";

// The files dotagents writes in a Codex home folder. Codex reads AGENTS.override.md instead of
// AGENTS.md when the first has text, so dotagents never writes it, only warns about it.
export const codexFiles = (home: string) => ({
  instructions: path.join(home, "AGENTS.md"),
  override: path.join(home, "AGENTS.override.md"),
});

type OnPath = () => boolean;
// Whether a codex command is on the PATH.
export const codexOnPath: OnPath = () =>
  (process.env.PATH ?? "").split(path.delimiter).some((dir) => dir && ["codex", "codex.cmd", "codex.exe"].some((n) => fs.existsSync(path.join(dir, n))));

// The sides where Codex is installed: this one (the command on the PATH, or its home folder) and
// the other one (its ~/.codex folder, since this side can't see its PATH).
type Side = { name: string; codexDir: string; platform: string };
function sides(onPath: OnPath, peer: Peer | undefined): Side[] {
  const here = codexHome();
  const out: Side[] = [];
  if (onPath() || fs.existsSync(here)) out.push({ name: "this side", codexDir: here, platform: process.platform });
  const there = peer && path.join(peer.home, ".codex");
  if (peer && there && fs.existsSync(there)) out.push({ name: peer.name, codexDir: there, platform: inWsl() ? "win32" : "linux" });
  return out;
}

// The instructions for a side, then each rule of the configuration under a heading of its own.
function codexInstructions(repo: string, platform: string) {
  const dir = path.join(configRoot(repo), "rules");
  const rules = fs.existsSync(dir) ? fs.readdirSync(dir).filter((n) => n.endsWith(".md")).sort() : [];
  const text = renderInstructions(repo, platform).trimEnd();
  if (!rules.length) return `${text}\n`;
  const body = rules.map((n) => fs.readFileSync(path.join(dir, n), "utf8").trim()).join("\n\n");
  return `${text}\n\n# Rules\n\nCodex has no rules folder, so the rules of the configuration follow here.\n\n${body}\n`;
}

// Applies the configuration to Codex on every side that has it: AGENTS.md (an older one dotagents
// generated is replaced, any other is backed up first). config.toml stays out: Codex writes to it
// itself.
export function installCodex(repo: string, { onPath = codexOnPath, peer = loadMachine().peer }: { onPath?: OnPath; peer?: Peer } = {}) {
  for (const side of sides(onPath, peer)) {
    section(`Codex configuration, ${side.name}`);
    writeGenerated(codexFiles(side.codexDir).instructions, codexInstructions(repo, side.platform), { onForeign: "backup" });
  }
}

// The checklist of that configuration: the instructions current, and nothing shadowing them.
export function verifyCodexConfig(repo: string, { onPath = codexOnPath, peer = loadMachine().peer }: { onPath?: OnPath; peer?: Peer } = {}) {
  for (const side of sides(onPath, peer)) {
    section(`Codex configuration, ${side.name}`);
    const files = codexFiles(side.codexDir);
    let current: string | null = null;
    try {
      current = fs.readFileSync(files.instructions, "utf8").replace(/\r\n/g, "\n");
    } catch {
      // Missing: said below.
    }
    const [marker = "", ...rest] = (current ?? "").split("\n");
    if (current === null) checkItem(false, `${displayPath(files.instructions)} is missing`, "write it with: dotagents install");
    else if (!marker.includes("generated by dotagents")) checkWarn(`${displayPath(files.instructions)} isn't generated by dotagents`, "install keeps a backup and replaces it: dotagents install");
    else checkItem(rest.join("\n") === codexInstructions(repo, side.platform), `${displayPath(files.instructions)} has the instructions and the rules`, "update it with: dotagents install");
    try {
      if (fs.readFileSync(files.override, "utf8").trim()) checkWarn(`${displayPath(files.override)} has text, so Codex reads it instead of AGENTS.md`, "remove it, or put what it says in the configuration");
    } catch {
      // No override: the normal case.
    }
  }
}
