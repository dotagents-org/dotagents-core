// Helpers shared by the `dotagents` commands.
// Every action is idempotent and honors --dry-run.
//
// Links: on Windows, folders become junctions (no admin rights needed) and files are copied,
// because file symlinks need admin rights or Developer Mode. On Linux and macOS, both folders
// and files become symlinks.

import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import { spawn, type SpawnOptions } from "node:child_process";
import { S_BAR, S_BAR_END, S_BAR_START, S_STEP_SUBMIT, spinner } from "@clack/prompts";
import pc from "picocolors";

export const isWindows = process.platform === "win32";

export type Status = keyof typeof STATUS;
export type Counts = Partial<Record<Status | "passed" | "warnings", number>>;
// base: folder that paths are shown relative to (the workspace, during init and check).
// silent: count results without printing them (used by the tests).
export const state: { dryRun: boolean; problems: number; counts: Counts; base: string | null; silent: boolean } = {
  dryRun: false,
  problems: 0,
  counts: {},
  base: null,
  silent: false,
};

export function resetState(overrides: Partial<typeof state> = {}) {
  Object.assign(state, { dryRun: false, problems: 0, counts: {}, base: null, silent: false }, overrides);
}

const MARKER = "<!-- generated by dotagents: edit the source in the dotagents repository and run it again -->";
// Earlier versions named the repository (<owner>/dotagents, <owner>/agents) or wrote the marker
// in Portuguese; all count as "generated by us".
const isOurs = (text: string) => text.startsWith("<!-- generated by dotagents");

// ── Terminal output ─────────────────────────────────────────────────────────────────────────
// In a terminal: the @clack/prompts look (one vertical rail from ┌ to └), icons, colors and short
// paths. Piped or redirected (CI, scripts): plain "<status> <path> (<detail>)" lines that are easy
// to grep. NO_COLOR turns colors off, FORCE_COLOR turns the terminal output on.

export const fancy = Boolean(process.stdout.isTTY) || Boolean(process.env.FORCE_COLOR);
// Prompts need a real keyboard, not just a colored output.
export const interactive = Boolean(process.stdin.isTTY && process.stdout.isTTY) && !process.env.CI;
const useColor = process.env.FORCE_COLOR ? true : fancy && !process.env.NO_COLOR;
export const style = pc.createColors(useColor);

// The rail: ┌ opens a command, │ carries every line, ◇ marks a section, └ closes.
export const rail = {
  bar: () => style.gray(S_BAR),
  start: () => style.gray(S_BAR_START),
  end: () => style.gray(S_BAR_END),
};
export const line = (text = "") => console.log(text ? `${rail.bar()}  ${text}` : rail.bar());

const STATUS = {
  ok: { icon: "✓", color: style.gray },
  created: { icon: "+", color: style.green },
  updated: { icon: "~", color: style.yellow },
  skipped: { icon: "!", color: style.yellow },
  failed: { icon: "✗", color: style.red },
  "would create": { icon: "+", color: style.cyan },
  "would update": { icon: "~", color: style.cyan },
  moved: { icon: "→", color: style.green },
  "would move": { icon: "→", color: style.cyan },
} satisfies Record<string, { icon: string; color: (text: string) => string }>;

const home = os.homedir();

// Shows a path relative to state.base when inside it, with ~ for the home folder, and forward
// slashes. Only in a terminal: piped output keeps the full path.
export function displayPath(p: string): string {
  if (!fancy || !p || !path.isAbsolute(p)) return p;
  if (state.base) {
    const rel = path.relative(state.base, p);
    if (rel && !rel.startsWith("..") && !path.isAbsolute(rel)) return toSlash(rel);
    if (rel === "") return ".";
  }
  const relHome = path.relative(home, p);
  if (!relHome.startsWith("..") && !path.isAbsolute(relHome)) return toSlash(path.join("~", relHome));
  return toSlash(p);
}

// Shortens the workspace and home folders inside a detail text ("-> C:\Users\me\x" → "→ ~/x").
function displayDetail(detail: string) {
  if (!fancy) return detail;
  let text = detail.replace(/^-> /, "→ ");
  const swap = (from: string, to: string) => {
    for (const variant of new Set([from, toSlash(from)])) text = text.split(variant).join(to);
  };
  if (state.base) swap(state.base + path.sep, "");
  swap(home, "~");
  return text.replace(/\\/g, "/");
}

export function report(status: Status, target: string, detail = "") {
  if (status === "skipped" || status === "failed") state.problems++;
  state.counts[status] = (state.counts[status] ?? 0) + 1;
  if (state.silent) return;
  if (!fancy) return console.log(`${status.padEnd(13)}${target}${detail ? `  (${detail})` : ""}`);
  const { icon, color } = STATUS[status];
  const shown = displayPath(target);
  const text = `${color(icon)} ${color(status.padEnd(12))} ${status === "ok" ? style.gray(shown) : shown}`;
  line(detail ? `${text}  ${style.dim(displayDetail(detail))}` : text);
}

// One checklist line: ✓ passed, ✗ failed (with the reason on the next line).
export function checkItem(passed: boolean, text: string, detail = "") {
  if (!passed) state.problems++;
  state.counts[passed ? "passed" : "failed"] = (state.counts[passed ? "passed" : "failed"] ?? 0) + 1;
  if (state.silent) return;
  if (!fancy) return console.log(`${(passed ? "ok" : "failed").padEnd(13)}${text}${!passed && detail ? `  (${detail})` : ""}`);
  if (passed) return line(`${style.green("✓")} ${style.gray(text)}`);
  line(`${style.red("✗")} ${text}`);
  if (detail) line(`  ${style.dim(`└ ${displayDetail(detail)}`)}`);
}

// A checklist note: shown with !, counted, but it doesn't fail the check.
export function checkWarn(text: string, detail = "") {
  state.counts.warnings = (state.counts.warnings ?? 0) + 1;
  if (state.silent) return;
  if (!fancy) return console.log(`${"warning".padEnd(13)}${text}${detail ? `  (${detail})` : ""}`);
  line(`${style.yellow("!")} ${text}`);
  if (detail) line(`  ${style.dim(`└ ${displayDetail(detail)}`)}`);
}

export function section(title: string) {
  if (state.silent) return;
  if (!fancy) return console.log(`
${title}`);
  line();
  console.log(`${style.cyan(S_STEP_SUBMIT)}  ${style.bold(title)}`);
}

// Opens a command: "┌  dotagents init  ~/projects/app".
export function header(command: string, subject = "") {
  if (!fancy) return;
  const dry = state.dryRun ? `  ${style.bgYellow(style.black(" dry run "))}` : "";
  const title = style.bgMagenta(style.white(style.bold(" dotagents ")));
  console.log(`${rail.start()}  ${title} ${style.bold(command)}${subject ? `  ${style.dim(displayPath(subject))}` : ""}${dry}`);
}

const pluralize = (n: number, word: string) => `${n} ${word}`;

// Closes a command with a summary: "└  ✓ 9 created · 2 already ok".
export function finish(hint = "") {
  const c = state.counts;
  if (fancy) {
    const parts = [
      c.passed && style.green(pluralize(c.passed, "passed")),
      c.created && style.green(pluralize(c.created, "created")),
      c.updated && style.yellow(pluralize(c.updated, "updated")),
      c.moved && style.green(pluralize(c.moved, "moved")),
      c["would move"] && style.cyan(pluralize(c["would move"], "to move")),
      c["would create"] && style.cyan(pluralize(c["would create"], "to create")),
      c["would update"] && style.cyan(pluralize(c["would update"], "to update")),
      c.ok && style.gray(pluralize(c.ok, "already ok")),
      c.skipped && style.yellow(pluralize(c.skipped, "skipped")),
      c.warnings && style.yellow(pluralize(c.warnings, c.warnings === 1 ? "warning" : "warnings")),
      c.failed && style.red(pluralize(c.failed, "failed")),
    ].filter(Boolean);
    const icon = state.problems ? style.red("✗") : style.green("✓");
    line();
    if (state.dryRun) line(style.yellow("Dry run: nothing was changed."));
    if (state.problems) line(style.dim("See the lines marked with ! or ✗ above."));
    if (hint) line(style.dim(hint));
    console.log(`${rail.end()}  ${icon} ${parts.join(style.gray(" · ")) || "done"}
`);
  } else {
    console.log("");
    if (state.dryRun) console.log("Dry run: nothing was changed.");
    if (state.problems) console.log(`${state.problems} item(s) skipped or failed: see the lines above.`);
    if (hint) console.log(hint);
  }
  process.exitCode = state.problems ? 1 : 0;
}

// Runs a command without blocking, so the spinner keeps turning. Returns the exit code and the
// last line of output (without colors).
export function runWithSpinner(
  message: string,
  command: string,
  commandArgs: string[],
  options: SpawnOptions = {},
): Promise<{ code: number; last: string }> {
  const spin = fancy ? spinner({ indicator: "dots" }) : null;
  spin?.start(message);
  return new Promise((resolve) => {
    const child = spawn(command, commandArgs, { ...options, stdio: ["ignore", "pipe", "pipe"] });
    let output = "";
    child.stdout.on("data", (d) => (output += d));
    child.stderr.on("data", (d) => (output += d));
    const done = (code: number | null) => {
      const last = output.replace(/\x1b\[[0-9;?]*[A-Za-z]/g, "").trim().split(/\r?\n/).pop() ?? "";
      if (spin) code === 0 ? spin.stop(style.dim(message)) : spin.error(message);
      resolve({ code: code ?? 1, last });
    };
    child.on("error", (err) => {
      output += err.message;
      done(1);
    });
    child.on("close", done);
  });
}

// The resolved path (links followed, Windows short names expanded), or null when it doesn't exist.
export function realpath(p: string) {
  try {
    return fs.realpathSync.native(p);
  } catch {
    return null;
  }
}

// lstat that returns null instead of throwing, and never follows links.
export function lstat(p: string) {
  try {
    return fs.lstatSync(p);
  } catch {
    return null;
  }
}

export function samePath(a: string, b: string) {
  const norm = (p: string) => path.resolve(p.replace(/^\\\\\?\\/, "")).replace(/[\\/]+$/, "");
  return isWindows ? norm(a).toLowerCase() === norm(b).toLowerCase() : norm(a) === norm(b);
}

function linkPointsTo(link: string, target: string) {
  try {
    const raw = fs.readlinkSync(link);
    return samePath(path.resolve(path.dirname(link), raw.replace(/^\\\\\?\\/, "")), target);
  } catch {
    return false;
  }
}

function removeLink(link: string) {
  // Deletes only the link, never the target's contents. Junctions need rmdir on Windows.
  try {
    fs.unlinkSync(link);
  } catch {
    fs.rmdirSync(link);
  }
}

function timestamp() {
  const d = new Date();
  const p = (n: number) => String(n).padStart(2, "0");
  return `${d.getFullYear()}${p(d.getMonth() + 1)}${p(d.getDate())}-${p(d.getHours())}${p(d.getMinutes())}${p(d.getSeconds())}`;
}

function backup(file: string) {
  const dest = `${file}.bak-${timestamp()}`;
  fs.renameSync(file, dest);
  return path.basename(dest);
}

function mkdirFor(file: string) {
  fs.mkdirSync(path.dirname(file), { recursive: true });
}

// Folder link: junction on Windows, symlink elsewhere. `relative` makes the symlink relative
// on Linux/macOS, so it survives moving the workspace; junctions are always absolute.
export function ensureDirLink(link: string, target: string, { relative = false } = {}) {
  const st = lstat(link);
  if (st?.isSymbolicLink()) {
    if (linkPointsTo(link, target)) return report("ok", link);
    if (state.dryRun) return report("would update", link, `-> ${target}`);
    removeLink(link);
    createDirLink(link, target, relative);
    return report("updated", link, `-> ${target}`);
  }
  if (st) return report("skipped", link, "a real folder or file with this name already exists");
  if (state.dryRun) return report("would create", link, `-> ${target}`);
  createDirLink(link, target, relative);
  report("created", link, `-> ${target}`);
}

function createDirLink(link: string, target: string, relative: boolean) {
  mkdirFor(link);
  if (isWindows) fs.symlinkSync(path.resolve(target), link, "junction");
  else fs.symlinkSync(relative ? path.relative(path.dirname(link), target) : path.resolve(target), link, "dir");
}

// File: symlink on Linux/macOS, copy on Windows. An existing different file is backed up first.
export function ensureFile(source: string, dest: string) {
  return isWindows ? syncCopy(source, dest) : ensureFileLink(source, dest);
}

function ensureFileLink(source: string, dest: string) {
  const st = lstat(dest);
  if (st?.isSymbolicLink() && linkPointsTo(dest, source)) return report("ok", dest);
  if (state.dryRun) return report(st ? "would update" : "would create", dest, `-> ${source}`);
  let detail = `-> ${source}`;
  if (st?.isSymbolicLink()) removeLink(dest);
  else if (st) detail += `, backup: ${backup(dest)}`;
  mkdirFor(dest);
  fs.symlinkSync(path.resolve(source), dest, "file");
  report(st ? "updated" : "created", dest, detail);
}

// Same content, ignoring line endings: an editor or an app on Windows may save the copy with CRLF,
// which isn't a change worth a backup.
const sameText = (a: string, b: string) => fs.readFileSync(a, "utf8").replace(/\r\n/g, "\n") === fs.readFileSync(b, "utf8").replace(/\r\n/g, "\n");

function syncCopy(source: string, dest: string) {
  const st = lstat(dest);
  if (st?.isFile() && sameText(source, dest)) return report("ok", dest);
  if (state.dryRun) return report(st ? "would update" : "would create", dest);
  let detail = "";
  if (st?.isSymbolicLink()) removeLink(dest);
  else if (st) detail = `backup: ${backup(dest)}`;
  mkdirFor(dest);
  fs.copyFileSync(source, dest);
  report(st ? "updated" : "created", dest, detail);
}

// Generated file, marked with MARKER. It is rewritten when it changes. A file without the
// marker belongs to the user: `onForeign: "skip"` leaves it alone, "backup" moves it aside.
export function writeGenerated(dest: string, content: string, { onForeign = "skip", skipNote = "" }: { onForeign?: "skip" | "backup"; skipNote?: string } = {}) {
  const full = `${MARKER}\n${content}`;
  const st = lstat(dest);
  let ours = false;
  if (st && !st.isSymbolicLink()) {
    const current = fs.readFileSync(dest, "utf8");
    if (current === full) return report("ok", dest);
    ours = isOurs(current);
    if (!ours && onForeign === "skip")
      return report("skipped", dest, skipNote || "already exists and was not generated by this repository");
  }
  if (state.dryRun) return report(st ? "would update" : "would create", dest);
  let detail = "";
  if (st?.isSymbolicLink()) removeLink(dest);
  else if (st && !ours) detail = `backup: ${backup(dest)}`;
  mkdirFor(dest);
  fs.writeFileSync(dest, full);
  report(st ? "updated" : "created", dest, detail);
}

// Sets one top-level key in a JSON file, keeping everything else. A key already set to another
// value is the user's choice and is left alone.
export function ensureJsonKey(file: string, key: string, value: unknown) {
  const st = lstat(file);
  let data: Record<string, unknown> = {};
  if (st) {
    try {
      data = JSON.parse(fs.readFileSync(file, "utf8"));
    } catch {
      return report("skipped", file, "not valid JSON");
    }
  }
  const shown = `${key}: ${JSON.stringify(value)}`;
  if (data[key] === value) return report("ok", file, shown);
  if (data[key] !== undefined) return report("skipped", file, `${key} is already set to ${JSON.stringify(data[key])}`);
  if (state.dryRun) return report(st ? "would update" : "would create", file, shown);
  data[key] = value;
  mkdirFor(file);
  fs.writeFileSync(file, `${JSON.stringify(data, null, 2)}\n`);
  report(st ? "updated" : "created", file, shown);
}

// Created from a template only when missing. After that the file belongs to the user.
// {{NAME}} placeholders in the template are filled from vars.
export function createFromTemplate(template: string, dest: string, vars: Record<string, string> = {}) {
  if (lstat(dest)) return report("ok", dest, "already exists, kept");
  if (state.dryRun) return report("would create", dest, `from ${path.basename(template)}`);
  mkdirFor(dest);
  const text = fs.readFileSync(template, "utf8").replace(/\{\{(\w+)\}\}/g, (m, key: string) => vars[key] ?? m);
  fs.writeFileSync(dest, text);
  report("created", dest, "template: edit the content");
}

export function ensureDir(dir: string) {
  if (lstat(dir)) return report("ok", dir);
  if (state.dryRun) return report("would create", dir);
  fs.mkdirSync(dir, { recursive: true });
  report("created", dir);
}

// Minimal argument parser: --flag, --key value, --key=value and positional arguments.
export type Args = { _: string[]; [key: string]: string | string[] | boolean | undefined };

// T names the options the caller declared, so it reads them without casts.
export function parseArgs<T extends Args = Args>(argv: string[], { booleans = [] as string[], lists = [] as string[] } = {}): T {
  const out: Args = { _: [] };
  for (let i = 0; i < argv.length; i++) {
    const arg = argv[i];
    if (!arg.startsWith("--")) {
      out._.push(arg);
      continue;
    }
    let [key, value] = arg.slice(2).split(/=(.*)/s, 2);
    if (booleans.includes(key)) {
      out[key] = true;
      continue;
    }
    if (value === undefined) value = argv[++i];
    if (value === undefined) throw new Error(`Missing value for --${key}`);
    out[key] = lists.includes(key) ? [...((out[key] as string[] | undefined) ?? []), ...value.split(/[,\s]+/).filter(Boolean)] : value;
  }
  return out as T;
}

export const toSlash = (p: string) => p.replace(/\\/g, "/");
